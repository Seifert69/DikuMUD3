#!/usr/bin/env python3
"""Spells for random potions, scrolls, wands and staffs (randomt.zon's rndSpells), by band.

    vme/scripts/spelltable.py [--md FILE]

Reads vme/etc/spells.def, updates vme/scripts/spell-table.tsv (a person edits its `band`, `use`
and `note` columns; the rest is computed and refreshed) and writes the spell lists into
vme/zone/randomt.zon between its "generated by spelltable.py" markers. --md also writes the
table as Markdown, by band, to read.

A spell's band (the treasure bands: average 0 to artifact 7, by player level 1-10, 11-15,
16-25, 26-40, 41-60, 61-80, 81-100, 101+) comes from the level it needs (`restrict level`),
else from the ability it needs (`restrict magic`/`restrict divine`, as a level: ability / 2),
else from its mana cost; `band` overrides it. `mediums` says which items may carry it.

use: no (never), once (potions and scrolls only: they are used once), or empty (any item its
mediums allow). Potions and scrolls carry a spell up to one band above the item, wands and
staffs up to their band, from one band below; a list of fewer than five reaches further down.
A potion carries only spells good for the drinker (an attack goes to a cursed potion); a staff
only attacks or spells good for their target, which do_use@skills sends to the user's group.
"""
import csv
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
VME = os.path.dirname(HERE)
SPELLS_DEF = os.path.join(VME, 'etc', 'spells.def')
RANDOMT = os.path.join(VME, 'zone', 'randomt.zon')
LEVEL_BANDS = [1, 11, 16, 26, 41, 61, 81, 101]
KINDS = ['potion', 'scroll', 'wand', 'staff']
COLS = ['index', 'name', 'sphere', 'offensive', 'targets', 'mana', 'needs', 'computed band'] + KINDS + ['band', 'use', 'note']
MANUAL = ['band', 'use', 'note']


def band_for_level(level):
    return max(b for b, start in enumerate(LEVEL_BANDS) if level >= start)


def parse(path):
    spells, cur = [], None
    for line in open(path):
        if line.lstrip().startswith('//'):
            continue
        m = re.match(r'\s*([a-z][a-z ]*?)\s*=\s*(.*)$', line.rstrip('\n'))
        if not m:
            continue
        k, v = m.group(1).strip(), m.group(2).split("//")[0].strip()
        if k == 'index':
            cur = {'index': v}
            spells.append(cur)
        elif cur is not None:
            cur[k] = v
    return [s for s in spells if s.get('func') and 'mediums' in s]


def main(md_path=None):
    old = {}
    path = os.path.join(HERE, 'spell-table.tsv')
    if os.path.exists(path):
        old = {r['index']: r for r in csv.DictReader(open(path), delimiter='\t')}
    rows = []
    for s in parse(SPELLS_DEF):
        if 'restrict level' in s:
            lvl, needs = int(s['restrict level']), f"level {s['restrict level']}"
        elif 'restrict magic' in s or 'restrict divine' in s:
            ab = int(s.get('restrict magic') or s.get('restrict divine'))
            lvl, needs = max(1, ab // 2), f"{'magic' if 'restrict magic' in s else 'divine'} {ab}"
        else:
            lvl, needs = max(1, int(s.get('mana', '20')) - 10), f"(mana {s.get('mana')})"
        r = {'index': s['index'], 'name': s['name'], 'sphere': s.get('sphere', '').replace('SPL_', '').lower(),
             'offensive': 'yes' if s.get('offensive') == 'TRUE' else '', 'targets': s.get('targets', ''),
             'mana': s.get('mana', ''), 'needs': needs, 'computed band': band_for_level(lvl)}
        for k in KINDS:
            r[k] = 'x' if 'MEDIA_' + k.upper() in s['mediums'] else ''
        # A staff casts an attack on everyone around but the user's company and a spell good for
        # its target (TAR_AUTO_SELF) on the user's group (do_use@skills); anything else (create
        # food, light, condemn) once per stranger around makes no sense on a random staff
        if r['staff'] and not r['offensive'] and 'TAR_AUTO_SELF' not in r['targets']:
            r['staff'] = ''
        # A potion casts on the drinker: random potions only carry spells good for their target
        # that may be cast on oneself (an attack is a cursed potion; heal animal, entangle and the
        # like would do nothing or harm)
        if r['potion'] and r['offensive']:
            r['potion'] = 'cursed'
        elif r['potion'] and ('TAR_AUTO_SELF' not in r['targets'] or 'TAR_SELF_NONO' in r['targets']):
            r['potion'] = ''

        for c in MANUAL:
            r[c] = old.get(s['index'], {}).get(c, '')
        rows.append(r)
    rows.sort(key=lambda r: (int(r['band'] or r['computed band']), r['sphere'], r['name']))
    with open(path, 'w', newline='') as f:
        w = csv.DictWriter(f, COLS, delimiter='\t', lineterminator='\n')
        w.writeheader()
        w.writerows(rows)
    show = ['name', 'sphere', 'offensive', 'needs', 'computed band'] + KINDS + ['use', 'note']
    md = ['# Spells for random magic items', '',
          'Made by `spelltable.py` from `spells.def`; edit `spell-table.tsv` (`band`, `use`: no to leave '
          'a spell out, once: only on one-use potions and scrolls, never on wands or staffs; `note`). One-use items may also carry a spell one band above their own (as a boss drop may). A spell goes on the items its `mediums` allow (x); random potions only help the drinker (an offensive one is a `cursed` potion).', '']
    for b in range(8):
        sel = [r for r in rows if int(r['band'] or r['computed band']) == b]
        md += [f'## Band {b} ({len(sel)} spells)', '', '| ' + ' | '.join(show) + ' |', '|' + '---|' * len(show)]
        md += ['| ' + ' | '.join(str(r[c]) for c in show) + ' |' for r in sel]
        md.append('')
    if md_path:
        open(md_path, 'w').write('\n'.join(md))
    print(f'{len(rows)} spells:', ', '.join(f'band {b} {sum(int(r["band"] or r["computed band"]) == b for r in rows)}' for b in range(8)))


CURSED = ['blind', 'sleep', 'fear', 'confusion', 'hold']  # they wear off; Papi: a careful-drinker trap


def lists(rows):
    """{(kind, band): [spell index...]} for random magic items, and the cursed potions' spells."""
    out = {}
    for ki, k in enumerate(KINDS):
        once_ok = k in ('potion', 'scroll')
        for b in range(8):
            lo, hi = b - 1, b + 1 if once_ok else b
            while True:
                sel = [r['index'] for r in rows if r[k] == 'x' and r['use'] != 'no' and (once_ok or r['use'] != 'once')
                       and lo <= int(r['band'] or r['computed band']) <= hi]
                if len(sel) >= 5 or lo < 0:
                    break
                lo -= 1  # few spells at this band: reach lower
            out[(ki, b)] = sel
    cursed = [r['index'] for r in rows if r['name'] in CURSED and r['potion'] == 'cursed']
    return out, cursed


def write_dil(rows, zonefile):
    out, cursed = lists(rows)
    code = ['// BEGIN generated by vme/scripts/spelltable.py from vme/scripts/spell-table.tsv: edit that, not this',
            '// The spells random magic items of kind (0 potion, 1 scroll, 2 wand, 3 staff) and band carry;',
            '// kind 4: a cursed potion\'s.',
            'dilbegin intlist rndSpells(kind : integer, band : integer);',
            'code', '{']
    for (ki, b), sel in sorted(out.items()):
        code.append(f'    if ((kind == {ki}) and (band == {b}))')
        code.append('        return ({' + ', '.join(sel) + '});')
    code.append('    return ({' + ', '.join(cursed) + '});')
    code += ['}', 'dilend', '// END generated by spelltable.py']
    z = open(zonefile).read()
    a, b = z.find('// BEGIN generated by'), z.find('// END generated by spelltable.py')
    block = '\n'.join(code)
    if a < 0 or b < 0:
        sys.exit(f'{zonefile}: no "// BEGIN generated by" / "// END generated by spelltable.py" markers')
    z = z[:a] + block + z[b + len('// END generated by spelltable.py'):]
    open(zonefile, 'w').write(z)
    print(f'{os.path.relpath(zonefile)}: rndSpells written')


if __name__ == '__main__':
    if len(sys.argv) not in (1, 3) or (len(sys.argv) == 3 and sys.argv[1] != '--md'):
        sys.exit(__doc__)
    main(sys.argv[2] if len(sys.argv) == 3 else None)
    write_dil(list(csv.DictReader(open(os.path.join(HERE, 'spell-table.tsv')), delimiter='\t')), RANDOMT)
